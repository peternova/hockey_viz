export function termById(id: string): GlossaryTerm | undefined {
  return GLOSSARY.find((t) => t.id === id);
}

/** Default sources when a term doesn't list its own. */
export function termSources(t: GlossaryTerm): string[] {
  if (t.sources) return t.sources;
  return t.category === 'rules' || t.category === 'pitch' || t.rule
    ? ['fih-2027', 'coaching-consensus']
    : ['coaching-consensus', 'ha-coaching'];
}
